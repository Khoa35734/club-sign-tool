  test('Functional simulation: PDF.js extracts pageCount and dimensions for single-page A4 PDF', async () => {
    const loadingTask = pdfjsLib.getDocument({
      data: getSinglePageA4Pdf(),
      useSystemFonts: true,
      isEvalSupported: false,
    });
    const pdfDoc = await loadingTask.promise;

    assert.equal(pdfDoc.numPages, 1, 'Single-page PDF must have 1 page');

    const page = await pdfDoc.getPage(1);
    const viewport = page.getViewport({ scale: 1.0 });

    const widthPt = Math.round(viewport.width * 100) / 100;
    const heightPt = Math.round(viewport.height * 100) / 100;

    // ISO 216 A4 points: 595.28 x 841.89
    assert.equal(widthPt, 595.28, 'A4 width in points must be 595.28');
    assert.equal(heightPt, 841.89, 'A4 height in points must be 841.89');
    assert.equal(page.rotate, 0, 'Initial rotation must be 0 degrees');
  });

